#!/usr/bin/env bash
set -euo pipefail

# Populate the offline Maven repository that the NextCraft Forge Android bundle ships at /root/maven/localMvnRepository.
#
# It builds the two project templates of AndroidProjectTemplateGenerator (COMPOSE and VIEWS) natively on x86_64 with the
# official Linux JDK, Gradle, and Android SDK, in a fresh GRADLE_USER_HOME, then harvests every artifact Gradle resolved
# (`caches/modules-2/files-2.1/<group>/<artifact>/<version>/<hash>/<file>`) into a Maven layout
# (`<group/path>/<artifact>/<version>/<file>`): `.pom`, `.module`, `.jar`, `.aar`, and the `*.gradle.plugin` markers.
#
# The templates are generated by the app's own Kotlin code (compiled here with kotlinc), so the cache always matches
# what the app writes. No root is needed. Runs on x86_64 Linux only: the Android SDK has no Linux ARM64 build.
#
#   ./build-android-maven-cache.sh
#
# Environment:
#   NEXTCRAFT_MAVEN_OUT   output directory (default: dist/runtime-bundles/android-maven-<version>)
#   NEXTCRAFT_WORK_DIR    parent for the mktemp work directory
#   NEXTCRAFT_KEEP_WORK   1 keeps the work directory
#   NEXTCRAFT_DOWNLOADS   cache directory for the downloaded archives (default: <work>/downloads)
#   JAVA_TOOL_OPTIONS     honoured by Gradle and sdkmanager (e.g. a proxy trust store); nothing from it enters the output.
#
# Versions here must match app/src/main/java/com/nextcraft/forge/runtime/AndroidToolchain.kt. Changing a template
# dependency version there without rebuilding this cache (and the Android bundle) breaks offline builds.

BUNDLE_VERSION="${NEXTCRAFT_ANDROID_BUNDLE_VERSION:-2026.10.1}"
GRADLE_VERSION="9.8.1"
GRADLE_URL="https://services.gradle.org/distributions/gradle-${GRADLE_VERSION}-bin.zip"
GRADLE_SHA256="dce76f55f8e251a3a1f130eb120f30b3d271de2b76c9b0729d316b5a1b6dc01f"
# Temurin 21.0.12.1+1 x64 (api.adoptium.net); the bundle itself ships the aarch64 build of the same release.
JDK_URL="https://github.com/adoptium/temurin21-binaries/releases/download/jdk-21.0.12.1%2B1/OpenJDK21U-jdk_x64_linux_hotspot_21.0.12.1_1.tar.gz"
JDK_SHA256="ce79869e1307ed8ee1e2baa86a412b1eb5b75d10a01006d788a6f968bcfaee94"
JDK_DIR="jdk-21.0.12.1+1"
# Android SDK Command-line Tools 23.0 (repository2-3.xml publishes SHA-1 only; SHA-256 computed from that file).
CMDLINE_TOOLS_URL="https://dl.google.com/android/repository/commandlinetools-linux-16111833_latest.zip"
CMDLINE_TOOLS_SHA1="e025545c62a8e64c7559119566a569fb1dec5f60"
CMDLINE_TOOLS_SHA256="0877a1d048fe4a24efe2eff536ca4223f7adeb58648bb81909d33c446918cfa8"
# Kotlin compiler used only to run the template generator from the repository sources.
KOTLINC_URL="https://github.com/JetBrains/kotlin/releases/download/v2.4.21/kotlin-compiler-2.4.21.zip"
KOTLINC_SHA256="7cc140e76daf416a0424a5557f99afd7ca89ebd463ea1101261e3e01c33e75cd"
# sdkmanager verifies these against Google's repository checksums; build-android-bundle.sh pins the same archives.
SDK_PACKAGES=("platforms;android-37.2" "build-tools;36.0.0")
# Hash sdkmanager writes to licenses/android-sdk-license after accepting the SDK license.
SDK_LICENSE_HASH="24333f8a63b6825ea9c5514f83c2829b004d1fee"

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"
OUT_DIR="${NEXTCRAFT_MAVEN_OUT:-$ROOT_DIR/dist/runtime-bundles/android-maven-${BUNDLE_VERSION}}"
WORK_PARENT="${NEXTCRAFT_WORK_DIR:-}"
KEEP_WORK="${NEXTCRAFT_KEEP_WORK:-0}"
SOURCES="$ROOT_DIR/app/src/main/java/com/nextcraft/forge"

[[ "$(uname -s)-$(uname -m)" == "Linux-x86_64" ]] || { echo "This script needs x86_64 Linux (no Linux ARM64 Android SDK exists)" >&2; exit 1; }
for tool in curl unzip tar sha256sum sha1sum python3; do
  command -v "$tool" >/dev/null || { echo "$tool is required" >&2; exit 1; }
done
[[ -f "$SOURCES/runtime/AndroidProjectTemplateGenerator.kt" ]] || { echo "Template generator source not found" >&2; exit 1; }

work="$(mktemp -d ${WORK_PARENT:+-p "$WORK_PARENT"})"
downloads="${NEXTCRAFT_DOWNLOADS:-$work/downloads}"
cleanup() {
  # Only delete the directory this script created itself via mktemp.
  if [[ "$KEEP_WORK" != "1" && -n "$work" && "$work" != "/" ]]; then
    rm -rf --one-file-system -- "$work"
  else
    echo "Work directory kept: $work" >&2
  fi
}
trap cleanup EXIT
mkdir -p "$downloads"

# fetch URL SHA256 [SHA1]: downloads into $downloads (reusing a verified copy) and verifies the pinned checksum(s).
fetch() {
  local url="$1" sha256="$2" sha1="${3:-}" name file
  name="$(basename "${url%%\?*}")"
  file="$downloads/$name"
  if [[ ! -f "$file" ]] || ! echo "$sha256  $file" | sha256sum -c --status; then
    echo "Downloading $name" >&2
    curl -fsSL --retry 3 -o "$file.part" "$url"
    mv "$file.part" "$file"
  fi
  echo "$sha256  $file" | sha256sum -c --status || { echo "SHA-256 mismatch: $name" >&2; exit 1; }
  [[ -z "$sha1" ]] || echo "$sha1  $file" | sha1sum -c --status || { echo "SHA-1 mismatch: $name" >&2; exit 1; }
  printf '%s' "$file"
}

jdk_tar="$(fetch "$JDK_URL" "$JDK_SHA256")"
gradle_zip="$(fetch "$GRADLE_URL" "$GRADLE_SHA256")"
clt_zip="$(fetch "$CMDLINE_TOOLS_URL" "$CMDLINE_TOOLS_SHA256" "$CMDLINE_TOOLS_SHA1")"
kotlinc_zip="$(fetch "$KOTLINC_URL" "$KOTLINC_SHA256")"

echo "Preparing host toolchain"
mkdir -p "$work/tools" "$work/sdk" "$work/projects" "$work/gen"
tar -xzf "$jdk_tar" -C "$work/tools"
unzip -q "$gradle_zip" -d "$work/tools"
unzip -q "$clt_zip" -d "$work/tools"
unzip -q "$kotlinc_zip" -d "$work/tools"
export JAVA_HOME="$work/tools/$JDK_DIR"
export PATH="$JAVA_HOME/bin:$work/tools/gradle-$GRADLE_VERSION/bin:$work/tools/kotlinc/bin:$PATH"
export ANDROID_HOME="$work/sdk" ANDROID_SDK_ROOT="$work/sdk" GRADLE_USER_HOME="$work/gradle-home"
java -version 2>&1 | grep -q '"21\.' || { echo "Expected JDK 21" >&2; exit 1; }

echo "Installing SDK packages: ${SDK_PACKAGES[*]}"
sdkmanager="$work/tools/cmdline-tools/bin/sdkmanager"
# Accept the SDK license the way sdkmanager --licenses records it (the option is gone from cmdline-tools 23).
mkdir -p "$ANDROID_HOME/licenses"
printf '\n%s\n' "$SDK_LICENSE_HASH" > "$ANDROID_HOME/licenses/android-sdk-license"
"$sdkmanager" --sdk_root="$ANDROID_HOME" "${SDK_PACKAGES[@]}" >/dev/null

echo "Generating templates with AndroidProjectTemplateGenerator"
cat > "$work/gen/Main.kt" <<'EOF'
import com.nextcraft.forge.model.AndroidTemplate
import com.nextcraft.forge.runtime.AndroidProjectTemplateGenerator
import java.io.File

fun main(args: Array<String>) {
    AndroidProjectTemplateGenerator.generate(File(args[0], "compose"), "Sample Compose", AndroidTemplate.COMPOSE)
    AndroidProjectTemplateGenerator.generate(File(args[0], "views"), "Sample Views", AndroidTemplate.XML)
}
EOF
kotlinc -nowarn -d "$work/gen/gen.jar" \
  "$SOURCES/runtime/AndroidToolchain.kt" "$SOURCES/runtime/AndroidProjectTemplateGenerator.kt" \
  "$SOURCES/model/Models.kt" "$work/gen/Main.kt"
java -cp "$work/gen/gen.jar:$work/tools/kotlinc/lib/kotlin-stdlib.jar" MainKt "$work/projects"

# Maven Central and Google Maven rate-limit a fresh cache (HTTP 429). Every attempt resumes from what is cached, so a
# few retries with a pause finish the resolution; the result is the same set of pinned artifacts.
build_project() {
  local project="$1" attempt
  for attempt in 1 2 3 4 5 6; do
    if (cd "$work/projects/$project" && gradle -Dorg.gradle.jvmargs= --no-daemon --max-workers=2 --console=plain -q \
        assembleDebug assembleRelease); then
      return 0
    fi
    echo "Build of $project failed (attempt $attempt); retrying after a pause" >&2
    sleep 90
  done
  return 1
}
for project in compose views; do
  echo "Building template $project (assembleDebug assembleRelease)"
  build_project "$project"
  [[ -f "$work/projects/$project/app/build/outputs/apk/debug/app-debug.apk" ]] || { echo "No debug APK for $project" >&2; exit 1; }
done

echo "Harvesting Gradle module cache into Maven layout"
rm -rf "$OUT_DIR"
mkdir -p "$OUT_DIR"
python3 - "$GRADLE_USER_HOME/caches/modules-2/files-2.1" "$OUT_DIR" <<'EOF'
import hashlib
import shutil
import sys
from pathlib import Path

cache = Path(sys.argv[1])
out = Path(sys.argv[2])
# com.android.tools.build:aapt2:*:linux is the x86_64 aapt2; the device uses android.aapt2FromMavenOverride with the
# ARM64 binary from Build-Tools, so AGP never resolves it there. Sources/javadoc are never needed for a build.
skipped_groups = {"com.android.tools.build/aapt2"}
manifest = []
for group_dir in sorted(cache.iterdir()):
    for artifact_dir in sorted(group_dir.iterdir()):
        if f"{group_dir.name}/{artifact_dir.name}" in skipped_groups:
            continue
        for version_dir in sorted(artifact_dir.iterdir()):
            for hash_dir in sorted(version_dir.iterdir()):
                for file in sorted(hash_dir.iterdir()):
                    if file.name.endswith(("-sources.jar", "-javadoc.jar")) or not file.is_file():
                        continue
                    target = out / group_dir.name.replace(".", "/") / artifact_dir.name / version_dir.name / file.name
                    target.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copyfile(file, target)
                    manifest.append((target.relative_to(out).as_posix(), hashlib.sha256(file.read_bytes()).hexdigest()))
manifest.sort()
(out / "MANIFEST.sha256").write_text("".join(f"{sha}  {path}\n" for path, sha in manifest))
print(f"{len(manifest)} files, {sum(f.stat().st_size for f in out.rglob('*') if f.is_file()) // 1_000_000} MB")
EOF
[[ -f "$OUT_DIR/com/android/tools/build/gradle/9.4.1/gradle-9.4.1.pom" ]] || { echo "AGP is missing from the harvest" >&2; exit 1; }
echo "Maven cache created: $OUT_DIR"
